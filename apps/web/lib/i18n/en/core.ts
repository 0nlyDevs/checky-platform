const plural = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;

/** A distance in days, rounded the way a person says it (same rounding as the French). */
const span = (days: number) => {
  const n = Math.abs(days);
  if (n < 60) return plural(n, "day", "days");
  if (n < 730) return plural(Math.round(n / 30.44), "month", "months");
  return plural(Math.floor(n / 365), "year", "years");
};

